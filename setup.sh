#!/usr/bin/env sh
# Creates .env for a new Nixflow self-hosted install, with fresh random secrets.
# Run once, from this folder:   ./setup.sh [PUBLIC_URL] [ADMIN_URL]
#   e.g. ./setup.sh https://nixflow.example.com https://nixflow-admin.example.com
# Defaults: http://localhost:8080 and http://localhost:8081.
set -eu

cd "$(dirname "$0")"

if [ -f .env ]; then
	echo ".env already exists — not overwriting it (it holds your secrets)."
	echo "Delete it first only if this is a brand-new install with no data."
	exit 1
fi

command -v openssl >/dev/null 2>&1 || { echo "openssl is required"; exit 1; }

PUBLIC_URL="${1:-http://localhost:8080}"
ADMIN_URL="${2:-http://localhost:8081}"

rand() { openssl rand -hex "$1"; }
b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }

JWT_SECRET=$(rand 32)

# A Supabase API key is a long-lived HS256 JWT carrying a role.
jwt() {
	now=$(date +%s)
	exp=$((now + 10 * 365 * 24 * 3600)) # 10 years
	header=$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)
	payload=$(printf '{"role":"%s","iss":"supabase","iat":%d,"exp":%d}' "$1" "$now" "$exp" | b64url)
	sig=$(printf '%s.%s' "$header" "$payload" | openssl dgst -sha256 -hmac "$JWT_SECRET" -binary | b64url)
	printf '%s.%s.%s' "$header" "$payload" "$sig"
}

umask 077 # .env is readable by its owner only
cat > .env <<EOF
# Nixflow self-hosted settings — generated by setup.sh on $(date -u +%Y-%m-%d).
# KEEP THIS FILE SECRET and BACKED UP. Losing ENCRYPTION_KEY makes saved
# connection credentials unreadable; changing JWT_SECRET signs everyone out.

# Where people open Nixflow (and the admin portal).
PUBLIC_URL=${PUBLIC_URL}
ADMIN_URL=${ADMIN_URL}
HTTP_PORT=8080
ADMIN_HTTP_PORT=8081

# Secrets (generated)
POSTGRES_PASSWORD=$(rand 24)
JWT_SECRET=${JWT_SECRET}
ANON_KEY=$(jwt anon)
SERVICE_ROLE_KEY=$(jwt service_role)
ENCRYPTION_KEY=$(openssl rand -base64 32)

# Optional — see .env.example for what each does.
DISABLE_SIGNUP=false
EMAIL_AUTOCONFIRM=true
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
SMTP_ADMIN_EMAIL=
SMTP_SENDER_NAME=Nixflow
RESEND_API_KEY=
EMAIL_FROM=
ANTHROPIC_API_KEY=
OPENAI_API_KEY=
EOF

echo "Wrote .env (app: ${PUBLIC_URL}, admin portal: ${ADMIN_URL})."
echo "Next: docker compose up -d"
